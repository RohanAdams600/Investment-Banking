#!/usr/bin/env node
/**
 * One file to paste into the SQL Editor.
 *
 * Applying migrations properly means a migration tool with a history table.
 * This is for the case that keeps happening instead: the project is reachable
 * from a browser and not from wherever the work is being done, and somebody has
 * to get four files into a database by hand without missing one or running them
 * out of order.
 *
 *   node scripts/bundle-migrations.mjs 0030            # everything from 0030 on
 *   node scripts/bundle-migrations.mjs 0030 0032       # a closed range
 *
 * Wrapped in a single transaction, deliberately. Half of a migration set is a
 * worse state than none of it, and a schema that is partly 0033 is one nobody
 * can reason about — including the next run of this script.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'supabase/migrations';
const [from, to] = process.argv.slice(2);

if (!from) {
  console.error('Usage: node scripts/bundle-migrations.mjs <from> [to]   e.g. 0030 0034');
  process.exit(1);
}

const files = readdirSync(DIR)
  .filter((name) => name.endsWith('.sql'))
  .sort()
  .filter((name) => {
    const n = name.slice(0, 4);
    return n >= from && (to === undefined || n <= to);
  });

if (files.length === 0) {
  console.error(`No migrations in range ${from}${to ? `–${to}` : '+'}.`);
  process.exit(1);
}

const parts = [
  '-- ===========================================================================',
  `-- ${files.length} migration${files.length === 1 ? '' : 's'}, in order, in one transaction.`,
  '--',
  '-- Generated by scripts/bundle-migrations.mjs. Do not edit; regenerate.',
  '--',
  '-- Paste the whole thing into the Supabase SQL Editor and run it once.',
  '--',
  '-- Then run the verification block printed at the end. Do not skip it: a',
  '-- dashboard paste has silently applied nothing at least once in this',
  "-- project's history while reporting success, and a partly-applied schema",
  '-- looks identical to a working one until something reads a column that is',
  '-- not there.',
  '-- ===========================================================================',
  '',
  'begin;',
  '',
];

for (const file of files) {
  parts.push(
    '-- ---------------------------------------------------------------------------',
    `-- ${file}`,
    '-- ---------------------------------------------------------------------------',
    '',
    readFileSync(join(DIR, file), 'utf8').trimEnd(),
    '',
  );
}

parts.push('commit;', '');

const out = 'supabase/bundle.sql';
writeFileSync(out, parts.join('\n'));

console.log(`Wrote ${out} — ${files.length} migrations:`);
for (const file of files) console.log(`  ${file}`);
console.log('\nPaste it into the SQL Editor, run it, then run `pnpm verify:schema` output.');
